def emit(model: Model) -> str:
    def access(name: str) -> str:
        return "public" if model.is_public(name) else "internal"

    based = {u.name for u in model.unions if all(access(v.name) == access(u.name) for v in u.variants)}

    parts = [emit_enum(e, access(e.name)) for e in model.enums]
    parts += [emit_object(o, [u for u in model.unions_of(o) if u in based], [u for u in model.unions_of(o) if u not in based], access(o.name)) for o in model.objects]
    parts += [emit_union(u, access(u.name), u.name in based) for u in model.unions]
    return HEADER + constants(model.wire) + "\n" + "\n".join(parts)


def is_value_type(type_: Type) -> bool:
    if isinstance(type_, Constrained):
        return type_.kind in ("integer", "number", "boolean")
    return isinstance(type_, Enum) or type_ in ("integer", "number", "boolean")


def cs_type(type_: Type) -> str:
    match type_:
        case Constrained(kind):
            return CS_TYPES[kind]
        case Enum(_, name):
            return name
        case Free():
            return "JsonObject"
        case Array(item):
            return f"IReadOnlyList<{cs_type(item)}>"
        case Ref(name):
            return name
        case _:
            return CS_TYPES[type_]


def literal(value: float | None) -> str:
    return "null" if value is None else f"{float(value)!r}"


def parser(type_: Type) -> str:
    match type_:
        case Constrained(kind, minimum, exclusive_minimum, exclusive_maximum, min_length):
            args = [f"minimum: {literal(minimum)}"] if minimum is not None else []
            args += [f"exclusiveMinimum: {literal(exclusive_minimum)}"] if exclusive_minimum is not None else []
            args += [f"exclusiveMaximum: {literal(exclusive_maximum)}"] if exclusive_maximum is not None else []
            args += [f"minLength: {min_length}"] if min_length is not None else []
            return f"Wire.Limit({PARSERS[kind]}, {', '.join(args)})"
        case Const(value):
            return f'Wire.Const("{value}")'
        case Enum(_, name):
            return f"{name}Wire.FromJson"
        case Free():
            return "Wire.Free"
        case Array(item):
            return f"Wire.List({parser(item)})"
        case Ref(name):
            return f"{name}.FromJson"
        case _:
            return PARSERS[type_]


def node(type_: Type, expr: str) -> str:
    match type_:
        case Enum():
            return f"JsonValue.Create({expr}.ToWire())"
        case Ref():
            return f"{expr}.ToJson()"
        case Free():
            return f"{expr}.DeepClone()"
        case Array(item):
            return f"new JsonArray({expr}.Select(x => (JsonNode?){node(item, 'x')}).ToArray())"
        case _:
            return f"JsonValue.Create({expr})"


def prop_name(owner: str, wire: str) -> str:
    name = pascal(wire)
    return name + "Value" if name == owner else name


MEMBERS = {
    *("Raw", "FromJson", "ToJson", "Decode", "Wire", "JsonValue", "Clone", "Deconstruct", "EqualityContract", "Equals", "GetHashCode"),
    *("GetType", "MemberwiseClone", "PrintMembers", "ReferenceEquals", "ToString"),
}


def references(type_: Type) -> set[str]:
    match type_:
        case Ref(name):
            return {name}
        case Enum(_, name):
            return {name + "Wire"}
        case Array(item):
            return references(item)
        case _:
            return set()


def reserved(field: Field, fields: Sequence[Field]) -> set[str]:
    own = {field.type.name} if isinstance(field.type, Ref) else set()
    return (MEMBERS | {name for f in fields for name in references(f.type)}) - own


NAMING = Naming(field=prop_name, reserved=reserved, value=value_name)


def emit_enum(enum: Enum, access: str) -> str:
    names = enum.value_names
    reads = "\n".join(f'            "{v}" => {enum.name}.{n},' for v, n in zip(enum.values, names))
    writes = "\n".join(f'            {enum.name}.{n} => "{v}",' for v, n in zip(enum.values, names))
    return f"""
{access} enum {enum.name}
{{
    {", ".join(names)},
}}

{access} static class {enum.name}Wire
{{
    public static {enum.name} FromJson(JsonNode? value) =>
        Wire.String(value) switch
        {{
{reads}
            var other => throw new FormatException($"unexpected value {{other}}"),
        }};

    public static string ToWire(this {enum.name} value) =>
        value switch
        {{
{writes}
            _ => throw new ArgumentOutOfRangeException(nameof(value)),
        }};
}}
"""


def emit_object(obj: Object, bases: list[str], interfaces: list[str], access: str) -> str:
    ordered = sorted(obj.typed, key=lambda f: not f.required)
    params = [
        f"{cs_type(f.type)} {prop_name(obj.name, f.name)}" if f.required else f"{cs_type(f.type)}? {prop_name(obj.name, f.name)} = null"
        for f in ordered
    ]
    params.append("JsonObject? Raw = null")
    checks = "".join(f'        Wire.Required(obj, "{f.name}", {parser(f.type)});\n' for f in obj.consts)
    if obj.exactly_one:
        keys = ", ".join(f'"{k}"' for k in obj.exactly_one)
        checks += f"        Wire.ExactlyOne(obj, {keys});\n"
    args = []
    for f in ordered:
        call = "Wire.Required" if f.required else ("Wire.OptionalValue" if is_value_type(f.type) else "Wire.Optional")
        read = parser(f.type)
        if f.tolerant:
            read = f"Wire.Tolerant({read}, value => new {cs_type(f.type)}(Raw: Wire.Snapshot(value)))"
        args.append(f'{call}(obj, "{f.name}", {read})')
    args.append("obj")
    writes = []
    for f in obj.typed:
        prop = prop_name(obj.name, f.name)
        if f.required:
            writes.append(
                f'        Wire.PutNumber(result, "{f.name}", {prop});' if is_number(f.type) else f'        result["{f.name}"] = {node(f.type, prop)};'
            )
        else:
            value = f"{prop}!.Value" if is_value_type(f.type) else f"{prop}!"
            put = f'Wire.PutNumber(result, "{f.name}", {value});' if is_number(f.type) else f'result["{f.name}"] = {node(f.type, value)};'
            writes.append(f'        if ({prop} is not null) {put}\n        else result.Remove("{f.name}");')
    writes += [f'        result["{f.name}"] = "{f.type.value}";' for f in obj.consts]
    supers = bases[:1] + [f"I{u}" for u in interfaces]
    base = f" : {', '.join(supers)}" if supers else ""
    hide = "new " if bases else ""
    override = "override " if bases else ""
    return f"""
{access} sealed record {obj.name}({", ".join(params)}){base}
{{
    public static {hide}{obj.name} FromJson(JsonNode? value)
    {{
        var obj = Wire.Snapshot(value);
{checks}        return new {obj.name}({", ".join(args)});
    }}

    public {override}JsonNode ToJson()
    {{
        var result = Wire.Copy(Raw);
{chr(10).join(writes)}
        return result;
    }}
}}
"""


def condition(variant: Variant) -> str | None:
    match variant.match:
        case Tag(value):
            return f'Wire.TagIs(obj, "{value}")'
        case Key(name):
            return f'Wire.Has(obj, "{name}")'
        case Always():
            return None


def emit_union(union: Union, access: str, base: bool) -> str:
    # A record cannot derive from a type less accessible than itself, so a union that holds a public variant
    # while being internal (the socket's messages, of which a few are public) is not a base type. Its variants
    # implement an internal interface instead, which a public record may do, and a static class decodes to it.
    name = union.name
    result = name if base else f"I{name}"
    branches = []
    for v in union.variants:
        cond = condition(v)
        if isinstance(v.match, Key):
            keys = ", ".join(f'"{k}"' for k in union.selectors)
            branches.append(f"        if ({cond})\n        {{\n            Wire.ExactlyOne(obj, {keys});\n            return {v.name}.FromJson(value);\n        }}")
            continue
        branches.append(f"        if ({cond}) return {v.name}.FromJson(value);" if cond else f"        return {v.name}.FromJson(value);")
    tail = "" if any(condition(v) is None for v in union.variants) else '        throw new FormatException("no variant matches");\n'
    unknown = ""
    decode = ""
    if union.open:
        unknown = f"""
{access} sealed record Unknown{name}(JsonObject Raw) : {name if base else "I" + name}
{{
    public {"override " if base else ""}JsonNode ToJson() => Raw.DeepClone();
}}
"""
        decode = f"""
    public static {result} Decode(JsonNode? value)
    {{
        var tree = Wire.Tree(value, out var unicode);
        try
        {{
            if (!unicode) throw new FormatException("a string holds a lone surrogate");
            return FromJson(tree);
        }}
        catch (FormatException)
        {{
            return new Unknown{name}(tree is JsonObject obj ? (JsonObject)obj.DeepClone() : new JsonObject());
        }}
    }}
"""
    if base:
        shape, name_, head = "abstract record", name, "    public abstract JsonNode ToJson();\n\n"
    else:
        shape, name_, head = "static class", name + "Wire", ""
    interface = "" if base else f"\ninternal interface I{name}\n{{\n    JsonNode ToJson();\n}}\n"
    return f"""{interface}
{access} {shape} {name_}
{{
{head}    public static {result} FromJson(JsonNode? value)
    {{
        var obj = Wire.Object(value);
{chr(10).join(branches)}
{tail}    }}
{decode}}}
{unknown}"""
