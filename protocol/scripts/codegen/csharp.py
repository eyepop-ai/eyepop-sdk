import re

from .model import Always, Array, Const, Enum, Field, Free, Key, Model, Object, Ref, Tag, Type, Union, Variant, pascal

HEADER = """// <auto-generated>Generated from protocol/schema by protocol/scripts/generate.py. Do not edit.</auto-generated>
#nullable enable
using System.Text.Json.Nodes;

namespace EyePop.Protocol;

internal static class Wire
{
    private static string Show(JsonNode? value) => value?.ToJsonString() ?? "null";

    public static JsonObject Object(JsonNode? value) =>
        value as JsonObject ?? throw new FormatException($"expected an object, got {Show(value)}");

    public static string String(JsonNode? value) =>
        value is JsonValue v && v.TryGetValue<string>(out var text) ? text : throw new FormatException($"expected a string, got {Show(value)}");

    public static long Integer(JsonNode? value) =>
        value is JsonValue v && v.TryGetValue<long>(out var number) ? number : throw new FormatException($"expected an integer, got {Show(value)}");

    public static double Number(JsonNode? value) =>
        value is JsonValue v && v.TryGetValue<double>(out var number) ? number : throw new FormatException($"expected a number, got {Show(value)}");

    public static bool Boolean(JsonNode? value) =>
        value is JsonValue v && v.TryGetValue<bool>(out var flag) ? flag : throw new FormatException($"expected a boolean, got {Show(value)}");

    public static JsonObject Free(JsonNode? value) => Object(value);

    public static Func<JsonNode?, string> Const(string expected) =>
        value => String(value) == expected ? expected : throw new FormatException($"expected \\"{expected}\\", got {Show(value)}");

    public static Func<JsonNode?, IReadOnlyList<T>> List<T>(Func<JsonNode?, T> item) =>
        value => value is JsonArray array
            ? array.Select(item).ToList()
            : throw new FormatException($"expected an array, got {Show(value)}");

    public static T Required<T>(JsonObject obj, string key, Func<JsonNode?, T> parse) =>
        obj.TryGetPropertyValue(key, out var value) ? parse(value) : throw new FormatException($"missing {key}");

    public static T? Optional<T>(JsonObject obj, string key, Func<JsonNode?, T> parse) where T : class =>
        obj.TryGetPropertyValue(key, out var value) ? parse(value) : null;

    public static T? OptionalValue<T>(JsonObject obj, string key, Func<JsonNode?, T> parse) where T : struct =>
        obj.TryGetPropertyValue(key, out var value) ? parse(value) : null;

    public static bool TagIs(JsonObject obj, string tag) =>
        obj["type"] is JsonValue v && v.TryGetValue<string>(out var text) && text == tag;

    public static bool Has(JsonObject obj, string key) => obj.ContainsKey(key);

    public static JsonObject Copy(JsonObject? raw) => raw is null ? new JsonObject() : (JsonObject)raw.DeepClone();
}
"""

CS_TYPES = {"string": "string", "integer": "long", "number": "double", "boolean": "bool"}
PARSERS = {"string": "Wire.String", "integer": "Wire.Integer", "number": "Wire.Number", "boolean": "Wire.Boolean"}


def emit(model: Model) -> str:
    enums = sorted({e.name: e for e in collect_enums(model)}.values(), key=lambda e: e.name)
    memberships = {
        obj.name: [u.name for u in model.unions if any(v.name == obj.name for v in u.variants)] for obj in model.objects
    }
    parts = [emit_enum(e) for e in enums]
    parts += [emit_object(o, memberships[o.name]) for o in model.objects]
    parts += [emit_union(u) for u in model.unions]
    return HEADER + "\n" + "\n".join(parts)


def collect_enums(model: Model) -> list[Enum]:
    found: list[Enum] = []

    def walk(type_: Type) -> None:
        if isinstance(type_, Enum):
            found.append(type_)
        elif isinstance(type_, Array):
            walk(type_.item)

    for obj in model.objects:
        for f in obj.fields:
            walk(f.type)
    return found


def variant_name(value: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^0-9A-Za-z]+", value) if part)


def is_value_type(type_: Type) -> bool:
    return isinstance(type_, Enum) or type_ in ("integer", "number", "boolean")


def cs_type(type_: Type) -> str:
    match type_:
        case Enum(_, name):
            return name
        case Free():
            return "JsonObject"
        case Array(item):
            return f"IReadOnlyList<{cs_type(item)}>"
        case Ref(name):
            return name
        case _:
            return CS_TYPES[type_]


def parser(type_: Type) -> str:
    match type_:
        case Const(value):
            return f'Wire.Const("{value}")'
        case Enum(_, name):
            return f"{name}Wire.FromJson"
        case Free():
            return "Wire.Free"
        case Array(item):
            return f"Wire.List({parser(item)})"
        case Ref(name):
            return f"{name}.FromJson"
        case _:
            return PARSERS[type_]


def node(type_: Type, expr: str) -> str:
    match type_:
        case Enum():
            return f"JsonValue.Create({expr}.ToWire())"
        case Ref():
            return f"{expr}.ToJson()"
        case Free():
            return f"{expr}.DeepClone()"
        case Array(item):
            return f"new JsonArray({expr}.Select(x => (JsonNode?){node(item, 'x')}).ToArray())"
        case _:
            return f"JsonValue.Create({expr})"


def prop_name(owner: str, f: Field) -> str:
    name = pascal(f.name)
    return name + "Value" if name == owner else name


def emit_enum(enum: Enum) -> str:
    names = [variant_name(v) for v in enum.values]
    reads = "\n".join(f'            "{v}" => {enum.name}.{n},' for v, n in zip(enum.values, names))
    writes = "\n".join(f'            {enum.name}.{n} => "{v}",' for v, n in zip(enum.values, names))
    return f"""
public enum {enum.name}
{{
    {", ".join(names)},
}}

public static class {enum.name}Wire
{{
    public static {enum.name} FromJson(JsonNode? value) =>
        Wire.String(value) switch
        {{
{reads}
            var other => throw new FormatException($"unexpected value {{other}}"),
        }};

    public static string ToWire(this {enum.name} value) =>
        value switch
        {{
{writes}
            _ => throw new ArgumentOutOfRangeException(nameof(value)),
        }};
}}
"""


def emit_object(obj: Object, unions: list[str]) -> str:
    consts = [f for f in obj.fields if isinstance(f.type, Const)]
    typed = [f for f in obj.fields if not isinstance(f.type, Const)]
    ordered = sorted(typed, key=lambda f: not f.required)
    params = [
        f"{cs_type(f.type)} {prop_name(obj.name, f)}" if f.required else f"{cs_type(f.type)}? {prop_name(obj.name, f)} = null"
        for f in ordered
    ]
    params.append("JsonObject? Raw = null")
    checks = "".join(f'        Wire.Required(obj, "{f.name}", {parser(f.type)});\n' for f in consts)
    args = []
    for f in ordered:
        call = "Wire.Required" if f.required else ("Wire.OptionalValue" if is_value_type(f.type) else "Wire.Optional")
        args.append(f'{call}(obj, "{f.name}", {parser(f.type)})')
    args.append("obj")
    writes = []
    for f in typed:
        prop = prop_name(obj.name, f)
        if f.required:
            writes.append(f'        result["{f.name}"] = {node(f.type, prop)};')
        else:
            value = f"{prop}!.Value" if is_value_type(f.type) else f"{prop}!"
            writes.append(f'        if ({prop} is not null) result["{f.name}"] = {node(f.type, value)};')
    writes += [f'        result["{f.name}"] = "{f.type.value}";' for f in consts]
    base = f" : {unions[0]}" if unions else ""
    hide = "new " if unions else ""
    override = "override " if unions else ""
    return f"""
public sealed record {obj.name}({", ".join(params)}){base}
{{
    public static {hide}{obj.name} FromJson(JsonNode? value)
    {{
        var obj = Wire.Object(value);
{checks}        return new {obj.name}({", ".join(args)});
    }}

    public {override}JsonNode ToJson()
    {{
        var result = Wire.Copy(Raw);
{chr(10).join(writes)}
        return result;
    }}
}}
"""


def condition(variant: Variant) -> str | None:
    match variant.match:
        case Tag(value):
            return f'Wire.TagIs(obj, "{value}")'
        case Key(name):
            return f'Wire.Has(obj, "{name}")'
        case Always():
            return None


def emit_union(union: Union) -> str:
    name = union.name
    branches = []
    for v in union.variants:
        cond = condition(v)
        branches.append(f"        if ({cond}) return {v.name}.FromJson(value);" if cond else f"        return {v.name}.FromJson(value);")
    tail = "" if any(condition(v) is None for v in union.variants) else '        throw new FormatException("no variant matches");\n'
    unknown = ""
    decode = ""
    if union.open:
        unknown = f"""
public sealed record Unknown{name}(JsonObject Raw) : {name}
{{
    public override JsonNode ToJson() => Raw.DeepClone();
}}
"""
        decode = f"""
    public static {name} Decode(JsonNode? value)
    {{
        try
        {{
            return FromJson(value);
        }}
        catch (FormatException)
        {{
            return new Unknown{name}(value as JsonObject ?? new JsonObject());
        }}
    }}
"""
    return f"""
public abstract record {name}
{{
    public abstract JsonNode ToJson();

    public static {name} FromJson(JsonNode? value)
    {{
        var obj = Wire.Object(value);
{chr(10).join(branches)}
{tail}    }}
{decode}}}
{unknown}"""
